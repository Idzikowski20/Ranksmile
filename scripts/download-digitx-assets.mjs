/**
 * Downloads DigitX marketing assets to public/marketing/digitx/
 * and rewrites lib/marketing/digitxAssets.ts with local paths.
 *
 * Usage: npm run digitx:assets
 */
import fs from 'node:fs';
import path from 'node:path';
import https from 'node:https';
import http from 'node:http';

const OUT_DIR = 'public/marketing/digitx';
const ASSETS_TS = 'lib/marketing/digitxAssets.ts';

function fetchUrl(url) {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith('https') ? https : http;
    lib.get(url, (res) => {
      if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        fetchUrl(res.headers.location).then(resolve).catch(reject);
        return;
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
      res.on('error', reject);
    }).on('error', reject);
  });
}

function extFromUrl(url) {
  const m = url.match(/\.(png|jpg|jpeg|svg|webp)(\?|$)/i);
  if (m) return `.${m[1].toLowerCase()}`;
  return '.png';
}

function slugFromUrl(url, key) {
  const id = url.split('/').pop()?.split('?')[0] ?? key;
  return `${key}-${id.slice(0, 8)}`;
}

async function downloadAsset(url, key) {
  const ext = extFromUrl(url);
  const filename = `${slugFromUrl(url, key)}${ext}`;
  const outPath = path.join(OUT_DIR, filename);
  if (fs.existsSync(outPath) && fs.statSync(outPath).size > 100) {
    return `/marketing/digitx/${filename}`;
  }
  try {
    const buf = await fetchUrl(url);
    if (buf.length < 50) throw new Error('too small');
    fs.writeFileSync(outPath, buf);
    return `/marketing/digitx/${filename}`;
  } catch (e) {
    console.warn(`Skip ${key}: ${e.message}`);
    return url;
  }
}

async function mapObject(obj, prefix = '') {
  if (typeof obj === 'string' && obj.startsWith('http')) {
    return downloadAsset(obj, prefix || 'asset');
  }
  if (Array.isArray(obj)) {
    return Promise.all(obj.map((v, i) => mapObject(v, `${prefix}${i}`)));
  }
  if (obj && typeof obj === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(obj)) {
      out[k] = await mapObject(v, prefix ? `${prefix}_${k}` : k);
    }
    return out;
  }
  return obj;
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const src = fs.readFileSync(ASSETS_TS, 'utf8');
  const match = src.match(/export const digitxAssets = (\{[\s\S]*?\})\s*(?:as const)?;/);
  if (!match) throw new Error('digitxAssets export not found');

  // eslint-disable-next-line no-eval
  const assets = eval(`(${match[1]})`);
  const local = await mapObject(assets);
  const out = `/** Self-hosted DigitX marketing assets (generated by scripts/download-digitx-assets.mjs) */\nexport const digitxAssets = ${JSON.stringify(local, null, 2)} as const;\n`;
  fs.writeFileSync(ASSETS_TS, out);
  console.log('DigitX assets updated:', OUT_DIR);
}

main().catch((e) => { console.error(e); process.exit(1); });
